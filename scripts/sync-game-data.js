#!/usr/bin/env node
/**
 * Sync the vendored Game Data snapshot from an Idle Fantasy checkout.
 *
 * Game Data is vendored rather than fetched at runtime so the app is
 * reproducible, works offline, and shows a reviewable diff when the game's data
 * changes.
 *
 * Usage:
 *   pnpm sync-game-data --source ~/Desktop/IdleFantasy    # refresh the snapshot
 *   pnpm sync-game-data --source ~/Desktop/IdleFantasy --check   # report drift only
 *   pnpm verify-game-data                                 # re-hash local files vs manifest
 *
 * --check exits 1 when the snapshot is stale (needs --source).
 * --verify exits 1 when a vendored file no longer matches its manifest hash
 *   (no --source, no network - catches accidental edits to the vendored files).
 */

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { humanize } from '../src/lib/humanize.ts';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const VENDOR_DIR = join(REPO_ROOT, 'public', 'game-data');
const MANIFEST = join(VENDOR_DIR, 'manifest.json');

const FILES = [
  'enemies.json',
  'quests.json',
  'raid_bosses.json',
  'equipment.json',
  'fish.json',
  'skills/fishing.json',
  'prestige_paths.json',
  'guild_quests.json',
  'pets.json',
  'buildings.json',
  'seasonal_events.json',
  'marketplace.json',
  'gems.json',
  'ores.json',
  'logs.json',
  'crops.json',
  'bones.json',
  'runes.json',
  'trees.json',
  'thieving_npcs.json',
  'agility_courses.json',
  'xp_table.json',
  'blessings.json',
  'recipes/smithing.json',
  'recipes/cooking.json',
  'recipes/fletching.json',
  'recipes/crafting.json',
  'recipes/herblore.json',
  'recipes/construction.json',
];

/**
 * Skilling dungeons ("expeditions") each ship a full drop table / xp curve we don't
 * use - the progress ledger only needs a display name, and completion is a fixed
 * 5-note threshold. Rather than vendor all 10 raw files, derive one small file.
 */
const SKILLING_DUNGEON_KEYS = [
  'abyssal_lagoon',
  'copper_caverns',
  'corrupted_canopy',
  'crumbling_watchtower',
  'dwarven_depths',
  'shadow_vault',
  'shattered_spire',
  'sunken_grotto',
  'thieves_den',
  'whispering_grove',
];
const EXPEDITION_NOTE_THRESHOLD = 5;
const EXPEDITIONS_OUTPUT = join(REPO_ROOT, 'src', 'lib', 'progress', 'expeditions-data.generated.ts');

const die = (msg) => {
  process.stderr.write(`error: ${msg}\n`);
  process.exit(1);
};

const sha256 = (path) => createHash('sha256').update(readFileSync(path)).digest('hex');

const dataDirOf = (source) => join(source, 'app', 'src', 'main', 'assets', 'data');

/** Read the game's version from its Gradle build file, plus its git commit. */
function gameVersion(source) {
  const gradle = readFileSync(join(source, 'app', 'build.gradle.kts'), 'utf8');
  const code = gradle.match(/versionCode\s*=\s*(\d+)/);
  const name = gradle.match(/versionName\s*=\s*"([^"]+)"/);
  let commit = null;
  try {
    commit = execFileSync('git', ['-C', source, 'rev-parse', 'HEAD'], {
      encoding: 'utf8',
    }).trim();
  } catch {
    commit = null;
  }
  return {
    version_code: code ? Number(code[1]) : null,
    version_name: name ? name[1] : null,
    commit,
  };
}

/**
 * Derive src/lib/progress/expeditions-data.generated.ts from the game's full
 * skilling_dungeons/*.json files: just the key list, plus label overrides for the rare
 * case where humanize(key) doesn't match the game's display_name (e.g. apostrophes).
 */
function buildExpeditionsTs(source) {
  const dataDir = dataDirOf(source);
  const missing = SKILLING_DUNGEON_KEYS.filter((k) => !existsSync(join(dataDir, 'skilling_dungeons', `${k}.json`)));
  if (missing.length) die(`skilling dungeons not found in ${dataDir}: ${missing.join(', ')}`);

  const overrides = {};
  for (const key of SKILLING_DUNGEON_KEYS) {
    const d = JSON.parse(readFileSync(join(dataDir, 'skilling_dungeons', `${key}.json`), 'utf8'));
    if (d.note_threshold !== EXPEDITION_NOTE_THRESHOLD) {
      die(
        `${key}: note_threshold is ${d.note_threshold}, expected ${EXPEDITION_NOTE_THRESHOLD} - ` +
          'the app hardcodes this threshold; update EXPEDITION_NOTE_THRESHOLD in ' +
          'src/lib/progress/categories.ts before syncing',
      );
    }
    if (d.display_name !== humanize(key)) overrides[key] = d.display_name;
  }

  const keysList = SKILLING_DUNGEON_KEYS.map((k) => `  '${k}',`).join('\n');
  const overrideLines = Object.entries(overrides)
    .map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`)
    .join('\n');

  return (
    '/**\n' +
    ' * Generated by scripts/sync-game-data.js. Do not edit by hand.\n' +
    ' *\n' +
    " * Derived from the game's skilling_dungeons/*.json - every expedition's display name is\n" +
    ' * dropped in favor of humanize(key), except where they disagree (see EXPEDITION_LABEL_OVERRIDES).\n' +
    ' */\n\n' +
    'export const EXPEDITION_KEYS = [\n' +
    keysList +
    '\n] as const;\n\n'
  );
}

function buildManifest(source) {
  const dataDir = dataDirOf(source);
  const missing = FILES.filter((f) => !existsSync(join(dataDir, f)));
  if (missing.length) die(`not found in ${dataDir}: ${missing.join(', ')}`);
  return {
    _comment:
      'Generated by scripts/sync-game-data.js. Game Data is vendored from ' +
      'tristinbaker/IdleFantasy (GPL-3.0) and kept unmodified. Do not edit by hand.',
    source: 'https://github.com/tristinbaker/IdleFantasy',
    game: gameVersion(source),
    files: Object.fromEntries(FILES.map((f) => [f, sha256(join(dataDir, f))])),
  };
}

function verify() {
  if (!existsSync(MANIFEST)) die('no manifest at public/game-data/manifest.json');
  const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));
  const bad = [];
  for (const [f, want] of Object.entries(manifest.files ?? {})) {
    const path = join(VENDOR_DIR, f);
    if (!existsSync(path)) bad.push(`${f} (missing)`);
    else if (sha256(path) !== want) bad.push(`${f} (hash mismatch)`);
  }
  if (bad.length) {
    for (const b of bad) console.error(`corrupt: ${b}`);
    console.error('\nvendored Game Data does not match manifest.json - restore from git');
    process.exit(1);
  }
  console.log(
    `ok: ${Object.keys(manifest.files ?? {}).length} files match manifest ` +
      `(game ${manifest.game?.version_name} / ${manifest.game?.version_code})`,
  );
}

function sameGame(a, b) {
  return JSON.stringify(a) === JSON.stringify(b);
}

function check(fresh) {
  if (!existsSync(MANIFEST)) {
    console.log('stale: no manifest; run without --check to create the snapshot');
    process.exit(1);
  }
  const current = JSON.parse(readFileSync(MANIFEST, 'utf8'));
  const drift = Object.entries(fresh.files)
    .filter(([f, h]) => current.files?.[f] !== h)
    .map(([f]) => f);
  const gone = Object.keys(current.files ?? {}).filter((f) => !(f in fresh.files));

  if (!drift.length && !gone.length && sameGame(current.game, fresh.game)) {
    console.log(`up to date with game ${fresh.game.version_name} (${fresh.game.version_code})`);
    return;
  }
  if (!sameGame(current.game, fresh.game)) {
    console.log(`game version changed: ${JSON.stringify(current.game)} -> ${JSON.stringify(fresh.game)}`);
  }
  for (const f of drift) console.log(`changed: ${f}`);
  for (const f of gone.sort()) console.log(`no longer vendored: ${f}`);
  console.log('\nsnapshot is stale; re-run without --check, then review the diff');
  process.exit(1);
}

function sync(source, fresh) {
  const dataDir = dataDirOf(source);
  for (const f of FILES) {
    const dest = join(VENDOR_DIR, f);
    mkdirSync(dirname(dest), { recursive: true });
    copyFileSync(join(dataDir, f), dest);
  }
  writeFileSync(MANIFEST, JSON.stringify(fresh, null, 2) + '\n');
  writeFileSync(EXPEDITIONS_OUTPUT, buildExpeditionsTs(source));

  const kb = FILES.reduce((n, f) => n + statSync(join(VENDOR_DIR, f)).size, 0) / 1024;
  console.log(
    `synced ${FILES.length} files (${kb.toFixed(0)} KB) from game ` +
      `${fresh.game.version_name} (${fresh.game.version_code})`,
  );
  if (fresh.game.commit) console.log(`upstream commit ${fresh.game.commit.slice(0, 12)}`);
  console.log('review the diff before committing - a data change can move every projection');
}

function main() {
  const { values } = parseArgs({
    options: {
      source: { type: 'string' },
      check: { type: 'boolean', default: false },
      verify: { type: 'boolean', default: false },
    },
  });

  if (values.verify) return verify();

  if (!values.source) die('--source <path to an IdleFantasy checkout> is required');
  const source = resolve(values.source.replace(/^~(?=$|\/)/, process.env.HOME ?? '~'));
  if (!existsSync(dataDirOf(source))) {
    die(`${source} does not look like an IdleFantasy checkout`);
  }

  const fresh = buildManifest(source);
  if (values.check) check(fresh);
  else sync(source, fresh);
}

main();
